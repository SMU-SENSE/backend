-- 추천 모델(model.json)이 참조하는 카드 ID와 커스텀 카드 소유자. 기존 행은 card_code 가 비어 있을 수 있다.
ALTER TABLE symbols ADD COLUMN card_code VARCHAR(100);
ALTER TABLE symbols ADD COLUMN owner_user_id BIGINT;
ALTER TABLE symbols ADD CONSTRAINT uk_symbol_card_code UNIQUE (card_code);
ALTER TABLE symbols ADD CONSTRAINT fk_symbol_owner_user FOREIGN KEY (owner_user_id) REFERENCES aac_users (id);
CREATE INDEX idx_symbols_owner_user ON symbols (owner_user_id);

-- 문장(카드 묶음) 단위 사용 기록. 개인 n-gram 복원용이라 카드 순서만 저장하고 변환 문장은 저장하지 않는다.
CREATE TABLE utterance_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    card_codes VARCHAR(2000) NOT NULL,
    converted BOOLEAN NOT NULL,
    spoken BOOLEAN NOT NULL,
    occurred_at TIMESTAMP(6) NOT NULL,
    CONSTRAINT fk_utterance_user FOREIGN KEY (user_id) REFERENCES aac_users (id)
);

CREATE INDEX idx_utterance_user_time ON utterance_logs (user_id, occurred_at);
